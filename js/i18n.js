  var LANGS = ['fr', 'ar', 'en'];
  var KEY = 'usa_lang';

  // French is the default on every new visit. A language picked with the switcher is kept
  // only while browsing (sessionStorage), so pages stay in that language until the tab is closed.
  // A link can still force a language: ?lang=ar or ?lang=en.
  try { localStorage.removeItem(KEY); } catch (e) { /* clear the old permanent choice */ }

  function readLang() {
    try {
      var q = new URLSearchParams(location.search).get('lang');
      if (q && LANGS.indexOf(q) > -1) return q;
    } catch (e) { /* ignore */ }
    try {
      var s = sessionStorage.getItem(KEY);
      if (s && LANGS.indexOf(s) > -1) return s;
    } catch (e) { /* ignore */ }
    return 'fr';
  }

  var lang = readLang();

  function t(key, vars) {
    var s = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.fr[key] || key;
    if (vars) Object.keys(vars).forEach(function (k) { s = s.replace('{' + k + '}', vars[k]); });
    return s;
  }

  // Translate a data object { fr, ar, en } (or plain string).
  function tr(obj) {
    if (obj == null) return '';
    if (typeof obj === 'string') return obj;
    return obj[lang] || obj.fr || obj.en || '';
  }

  function applyDocument() {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.innerHTML = t(el.getAttribute('data-i18n'));
    });
    root.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(',').forEach(function (pair) {
        var p = pair.split(':');
        el.setAttribute(p[0].trim(), t(p[1].trim()));
      });
    });
    var title = document.querySelector('title[data-i18n]');
    if (title) document.title = t(title.getAttribute('data-i18n'));
  }

  function setLang(l) {
    if (LANGS.indexOf(l) < 0 || l === lang) return;
    lang = l;
    try { sessionStorage.setItem(KEY, l); } catch (e) { /* ignore */ }
    applyDocument();
    apply();
    document.dispatchEvent(new CustomEvent('langchange', { detail: l }));
  }

  applyDocument();

  window.USAI18n = {
    t: t, tr: tr, apply: apply, setLang: setLang, langs: LANGS,
    get lang() { return lang; },
    locale: function () { return lang === 'ar' ? 'ar-MA' : lang === 'en' ? 'en-GB' : 'fr-FR'; }
  };
